    # ---- what the release is allowed to claim about itself -------------------

    def test_deployable_flag_contradicting_the_gate_is_rejected(self):
        """release.json used to be written false unconditionally while
        gates/package.ok said the gate had passed."""
        path = self.rel / "release.json"
        doc = json.loads(path.read_text())
        doc["deployable"] = True
        path.write_text(json.dumps(doc))
        self.assert_rejected(self.result(), "contradicts itself")

    def test_release_may_not_claim_hardware_or_deployment_acceptance(self):
        """No package gate has ever touched a card. A field that says otherwise is a
        fabricated PASS, whatever the surrounding prose says."""
        for key in ("hardware_accepted", "deployment_accepted"):
            path = self.rel / "release.json"
            doc = json.loads(path.read_text())
            doc[key] = True
            path.write_text(json.dumps(doc))
            self.assert_rejected(self.result(), "hardware/deployment acceptance")
            doc[key] = False
            path.write_text(json.dumps(doc))

    def test_gate_result_names_the_runbook_instead_of_claiming_acceptance(self):
        result = self.result()
        self.assertEqual(result["verdict"], "RELEASE_GATE_PASS", result["errors"])
        self.assertIn("sc7f0_release_deploy_acceptance_runbook.md",
                      result["hardware_acceptance"])


