#!/usr/bin/env python3
"""Negative tests for the release gate, against a synthetic release directory.

scripts/check_sc7f0_release_package.py --self-test mutates a *real* release; this
module proves the gate logic itself, so the defects it must catch are covered even
before a real release exists:

  * a boot member missing from the tar or from images/
  * a payload byte changed under an unchanged manifest
  * manifest.sha256 removed from the tar
  * bitstream that hardware.xsa does not carry
  * PS image declared as built from a different XSA
  * strict gate record absent
  * a FORGED gate record: JSON claims pass while the release's own reports say
    otherwise (the reports here are a real archived failing report set)
  * version / identity / provenance disagreeing about what this release is
  * a runtime binary that image.ub does not contain
  * release.json hashes that do not match the files they name
  * GNU/PAX tar headers instead of strict ustar

The passing timing fixture is a real archived routed report set from this
repository; if none is present the gate tests skip with a reason rather than pass.
"""
from __future__ import annotations

