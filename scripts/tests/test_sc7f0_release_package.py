import io
import json
from pathlib import Path
import shutil
import sys
import tarfile
import tempfile
import unittest

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "scripts"))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_sc7f0_release_package as gate  # noqa: E402
from test_sc7f0_fit_rootfs import fit  # noqa: E402

TIMING_REPORTS = ("timing_summary.rpt", "check-timing.rpt", "cdc.rpt",
                  "methodology.rpt", "bus-skew.rpt")
# Layer B inputs: without these the two-layer verdict cannot even be re-derived,
# so a release that lacks them is not gradable (B1 review P1-6: the flow used to
# produce none of them).
EXTRA_REPORTS = ("drc.rpt", "clock-interaction.rpt", "clock-networks.rpt",
                 "exceptions-coverage.rpt", "exceptions-ignored.rpt",
                 "exceptions-scope-override.rpt", "io.rpt",
                 "utilization_routed_hierarchical.rpt")
POLICY_SNAPSHOT = ("sc7f0_cdc_review.json", "sc7f0_drc_review.json",
                   "sc7f0_clock_pair_review.json", "sc7f0_review_policy.py")
FAIL_FIXTURE = REPO / "build/qpcie_zu4ev_hdmi_proj"
VERSION = "26991201"


def sha(b: bytes) -> str:
    return hashlib.sha256(b if isinstance(b, bytes) else b.read_bytes()).hexdigest()


def make_tar(members: list[tuple[str, bytes]]) -> bytes:
    """Strict ustar archive, no PAX/GNU extension headers."""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=tarfile.USTAR_FORMAT) as arc:
        for name, data in members:
            info = tarfile.TarInfo(name)
            info.size = len(data)
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            info.mtime = 1700000000
            info.type = tarfile.REGTYPE
            arc.addfile(info, io.BytesIO(data))
    out = buf.getvalue()
    return out + bytes((-len(out)) % 10240 or 10240)


def manifest_table(entries: list[tuple[str, bytes]]) -> bytes:
    return b"".join(f"{sha(d)}  {n}\n".encode() for n, d in entries)


def complete_fixture(work: Path) -> tuple[Path, Path]:
    """Return (report set, review-policy snapshot) for a baseline that passes.

    No real round in this repository can be the passing baseline any more: the
    archived report sets were produced before report_drc, report_clock_interaction
    and the exception reports were made mandatory, so they are correctly refused
    for lacking inputs. Fabricating those reports for a real round would be worse
    than useless. So the baseline is generated by the same fixture writer that
    scripts/tests/test_sc7f0_two_layer_gates.py proves is *refused* whenever a
    structure, a hash or a review claim is faked - and its policy snapshot is a
    reduced copy whose open items were removed, which is exactly the shape a real
    future passing release must have.
    """
    from test_sc7f0_two_layer_gates import Fixture, manifest_items, reduced_policy
    reports = work / "reports"
    policy = reduced_policy(work / "policy",
                            drop_io_statuses=("NEEDS_STRUCTURAL_REVIEW", "BLOCKED"))
    text = json.loads((policy / "sc7f0_cdc_review.json").read_text())
    Fixture(reports, items=manifest_items(text))
    return reports, policy


def unit_test_json(ident: dict) -> dict:
    """A gates/unit-tests*.json body that names these sources.

    The release gate requires three of them (preflight, after-fpga, at-package),
    each PASS, each with an empty required_tests_not_executed, and each recording
    the same fingerprints identity.json carries - otherwise a green suite from some
    earlier round is what grades this release.
    """
    return {"verdict": "UNIT_TESTS_GATE_PASS", "returncode": 0,
            "require_run": ["test_sc7f0_release_package", "test_sc7f0_fit_rootfs"],
            "ran": ["test_sc7f0_release_package.ReleaseGateTests.test_baseline_release_passes",
                    "test_sc7f0_fit_rootfs.FitReaderTests.test_verify_passes_on_a_complete_runtime"],
            "skipped": [], "unexpected_failures": [], "stale_baseline_entries": [],
            "required_tests_not_executed": [],
            "tolerated": ["test_sc7f0_mcu_app_image.AppImageTests.test_wrong_stack"],
            "baseline_reasons": {"test_sc7f0_mcu_app_image.AppImageTests.test_wrong_stack":
                                 "NUC1262 MCU subsystem, out of scope for this release"},
            "sources": {k: ident[k] for k in
                        ("source_fingerprint_sha256", "fpga_scope_fingerprint_sha256",
                         "ps_scope_fingerprint_sha256")}}


def write_source_manifests(rel: Path) -> None:
    """SOURCE.sha256 + the two role manifests + the snapshot that must contain them.

    Built from scripts/sc7f0_release_id.py's own declared required set, so the test
    cannot drift away from the real requirement (and a newly required input is
    automatically covered here).
    """
    sys.path.insert(0, str(REPO / "scripts"))
    import sc7f0_release_id as rid
    members: dict[str, bytes] = {}
    roles: dict[str, set[str]] = {"SOURCE_FPGA.sha256": set(),
                                 "SOURCE_VALIDATION.sha256": set()}
    for scope in ("fpga", "ps", "validation"):
        role = ("SOURCE_VALIDATION.sha256" if scope == "validation"
                else "SOURCE_FPGA.sha256")
        for name in rid.REQUIRED_SOURCE_FILES[scope]:
            members.setdefault(name, ("input bytes of " + name).encode())
            roles[role].add(name)
    tar = rel / "source-snapshot.tar.gz"
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w:gz") as arc:
        for name, data in sorted(members.items()):
            info = tarfile.TarInfo(name)
            info.size = len(data)
            arc.addfile(info, io.BytesIO(data))
    tar.write_bytes(buf.getvalue())
    table = {name: sha(data) for name, data in members.items()}
    (rel / "SOURCE.sha256").write_text(
        "".join(f"{table[n]}  {n}\n" for n in sorted(table)))
    for manifest, names in roles.items():
        (rel / manifest).write_text(
            "".join(f"{table[n]}  {n}\n" for n in sorted(names)))


